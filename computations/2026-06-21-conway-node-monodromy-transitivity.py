#!/usr/bin/env python3
"""
NODE experiment: transitivity of monodromy as connectedness of a cover.

Constraint under test:
  A permutation monodromy tuple defines a connected covering iff the subgroup
  generated by the local monodromies acts transitively on the sheets.

Experiment:
  Enumerate triples in S4 with product identity.  Find the same local cycle
  type passport with both transitive and non-transitive generated subgroup.
"""

from collections import defaultdict, deque
from itertools import permutations, product


N = 4
ID = tuple(range(N))


def compose(p, q):
    """p after q."""
    return tuple(p[q[i]] for i in range(N))


def inv(p):
    out = [0] * N
    for i, v in enumerate(p):
        out[v] = i
    return tuple(out)


def cycle_type(p):
    seen = [False] * N
    lengths = []
    for i in range(N):
        if seen[i]:
            continue
        cur = i
        length = 0
        while not seen[cur]:
            seen[cur] = True
            length += 1
            cur = p[cur]
        lengths.append(length)
    return tuple(sorted(lengths, reverse=True))


def generated_group(gens):
    group = {ID}
    queue = deque([ID])
    gens = list(gens) + [inv(g) for g in gens]
    while queue:
        g = queue.popleft()
        for h in gens:
            gh = compose(g, h)
            if gh not in group:
                group.add(gh)
                queue.append(gh)
    return group


def orbit(group, start=0):
    return {g[start] for g in group}


def transitive(gens):
    return len(orbit(generated_group(gens))) == N


def fmt_perm(p):
    return "(" + " ".join(str(i + 1) + "->" + str(p[i] + 1) for i in range(N)) + ")"


def main():
    perms = list(permutations(range(N)))
    buckets = defaultdict(lambda: {"T": None, "F": None})
    count = 0
    for a, b in product(perms, repeat=2):
        c = inv(compose(a, b))
        tup = (a, b, c)
        profile = tuple(cycle_type(x) for x in tup)
        is_trans = transitive(tup)
        key = "T" if is_trans else "F"
        if buckets[profile][key] is None:
            buckets[profile][key] = tup
        count += 1

    mixed = [(profile, vals) for profile, vals in buckets.items() if vals["T"] is not None and vals["F"] is not None]
    mixed.sort(key=lambda item: item[0])
    profile, vals = mixed[0]

    print("NODE: monodromy transitivity is connectedness")
    print(f"enumerated triples in S{N} with product identity: {count}")
    print(f"number of local cycle-type profiles with both connected and disconnected examples: {len(mixed)}")
    print()
    print(f"shared local cycle-type passport: {profile}")
    for label in ["T", "F"]:
        tup = vals[label]
        group = generated_group(tup)
        print(f"{'transitive' if label == 'T' else 'non-transitive'} example:")
        for idx, p in enumerate(tup, 1):
            print(f"  g{idx} type={cycle_type(p)} {fmt_perm(p)}")
        print(f"  product identity: {compose(compose(tup[0], tup[1]), tup[2]) == ID}")
        print(f"  generated group size={len(group)} orbit_of_1={sorted(x + 1 for x in orbit(group))}")
        print()

    print("Interpretation:")
    print("  The local branch passport and product-one relation do not determine")
    print("  connectedness.  The missing global constraint is transitivity of the")
    print("  generated monodromy action on sheets.")


if __name__ == "__main__":
    main()
