#!/usr/bin/env python3
"""
Attempt 3 transfer experiment.

ResearchNode: affine confinement.
NODE: monodromy connectedness requires transitivity of the generated action,
not just the local passport.

Transfer model:
  A finite exponent cloud S in Z^2 has an affine passport
      P(S) = (|S|, sum_{v in S} v).
  Within a fixed passport fiber, compare the lattice generated by differences
      L(S) = <v - v0 : v in S>.

The generated lattice index is invisible to the passport.  This is the finite
toy version of "local passport + balance relation is not enough; generated
action data matters".
"""

from __future__ import annotations

from collections import defaultdict
from itertools import combinations
from math import gcd
from collections import deque


Point = tuple[int, int]
Cloud = tuple[Point, ...]
Passport = tuple[int, Point]


def det(a: Point, b: Point) -> int:
    return a[0] * b[1] - a[1] * b[0]


def lattice_signature(cloud: Cloud) -> tuple[str, int | None]:
    """Return rank/index data for the difference lattice generated by cloud."""
    base = cloud[0]
    diffs = [(x - base[0], y - base[1]) for x, y in cloud[1:]]

    if not diffs:
        return ("rank0", None)

    nonzero = [v for v in diffs if v != (0, 0)]
    if not nonzero:
        return ("rank0", None)

    g = 0
    for a, b in combinations(nonzero, 2):
        g = gcd(g, abs(det(a, b)))

    if g == 0:
        return ("rank1", None)

    return ("rank2_index", g)


def difference_generators(cloud: Cloud) -> list[Point]:
    base = cloud[0]
    return [(x - base[0], y - base[1]) for x, y in cloud[1:]]


def nonzero_minors(cloud: Cloud) -> list[int]:
    minors: list[int] = []
    for a, b in combinations(difference_generators(cloud), 2):
        d = det(a, b)
        if d != 0:
            minors.append(d)
    return minors


def orbit_mod(cloud: Cloud, modulus: int) -> set[Point]:
    gens = difference_generators(cloud)
    start = (0, 0)
    seen = {start}
    queue: deque[Point] = deque([start])
    while queue:
        x, y = queue.popleft()
        for dx, dy in gens:
            for sx, sy in ((dx, dy), (-dx, -dy)):
                nxt = ((x + sx) % modulus, (y + sy) % modulus)
                if nxt not in seen:
                    seen.add(nxt)
                    queue.append(nxt)
    return seen


def passport(cloud: Cloud) -> Passport:
    sx = sum(x for x, _ in cloud)
    sy = sum(y for _, y in cloud)
    return (len(cloud), (sx, sy))


def enumerate_clouds(max_coord: int, size: int) -> dict[Passport, list[tuple[Cloud, tuple[str, int | None]]]]:
    grid = [(x, y) for x in range(max_coord + 1) for y in range(max_coord + 1)]
    fibers: dict[Passport, list[tuple[Cloud, tuple[str, int | None]]]] = defaultdict(list)

    for cloud in combinations(grid, size):
        c = tuple(sorted(cloud))
        fibers[passport(c)].append((c, lattice_signature(c)))

    return fibers


def mixed_fibers(max_coord: int, size: int) -> list[tuple[Passport, dict[tuple[str, int | None], Cloud], int]]:
    mixed: list[tuple[Passport, dict[tuple[str, int | None], Cloud], int]] = []
    for p, items in enumerate_clouds(max_coord, size).items():
        reps: dict[tuple[str, int | None], Cloud] = {}
        for cloud, sig in items:
            reps.setdefault(sig, cloud)
        if len(reps) > 1:
            mixed.append((p, reps, len(items)))
    return sorted(mixed, key=lambda item: (item[0][0], item[0][1], item[2]))


def main() -> None:
    print("AFFINE PASSPORT VS GENERATED LATTICE INDEX")
    print("passport P(S)=(|S|, sum S); invariant tested: index of <S-S> in Z^2")
    print()

    for max_coord, size in [(2, 3), (3, 3), (3, 4)]:
        mixed = mixed_fibers(max_coord, size)
        print(f"grid=[0,{max_coord}]^2 size={size}")
        print(f"  mixed passport fibers: {len(mixed)}")
        if mixed:
            p, reps, fiber_size = mixed[0]
            print(f"  first mixed passport: {p}; fiber size={fiber_size}")
            for sig, cloud in sorted(reps.items(), key=lambda item: str(item[0])):
                print(f"    signature={sig}: {cloud}")
        print()

    target = (3, (1, 2))
    target_items = enumerate_clouds(2, 3)[target]
    print("explicit same-passport witness in [0,2]^2:")
    for cloud, sig in target_items:
        if sig in {("rank2_index", 1), ("rank2_index", 2)}:
            print(f"  P={target}, signature={sig}, S={cloud}")
            print(f"    generator matrix columns={difference_generators(cloud)}")
            print(f"    nonzero 2x2 minors={nonzero_minors(cloud)}")
            print(f"    orbit on (Z/2Z)^2={sorted(orbit_mod(cloud, 2))}")


if __name__ == "__main__":
    main()
